package com.yesman.akythera.core.animation.playable;

import com.mojang.serialization.Codec;
import com.mojang.serialization.MapCodec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.yesman.akythera.api.component.ComponentAttachable;
import com.yesman.akythera.api.data.modularize.ScriptType;
import com.yesman.akythera.core.animation.driver.BlendSpace2DDriver;
import com.yesman.akythera.core.animation.keyframe.Pose;
import com.yesman.akythera.core.math.algorithm.DelaunayTriangulation;
import com.yesman.akythera.core.registry.AkytheraRegistries;
import com.yesman.akythera.core.util.StaticRegistryAccess;
import com.yesman.akythera.core.util.helper.MathUtils;
import com.yesman.akythera.core.util.helper.ParseUtils;
import net.minecraft.core.Holder;
import net.minecraft.resources.ResourceKey;
import org.jspecify.annotations.NonNull;
import org.jspecify.annotations.Nullable;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.function.Supplier;

/// A mixture of multiple animation nodes placed in 1D array shape
///
/// Inspired by [UE Blend Space](https://dev.epicgames.com/documentation/unreal-engine/blend-spaces-in-unreal-engine)
public final class BlendSpace2D implements PlayableAnimation {
    public static final MapCodec<BlendSpace2D> MAP_CODEC = RecordCodecBuilder.mapCodec(
        instance ->
            instance.group(
                Codec.FLOAT.fieldOf("fade_in_time").forGetter(BlendSpace2D::fadeInTime),
                Codec.FLOAT.fieldOf("fade_out_time").forGetter(BlendSpace2D::fadeOutTime),
                Codec.FLOAT.fieldOf("smooth_x").forGetter(BlendSpace2D::smoothX),
                Codec.FLOAT.fieldOf("smooth_y").forGetter(BlendSpace2D::smoothY),
                Codec.FLOAT.fieldOf("min_x").forGetter(BlendSpace2D::blendSpaceMinX),
                Codec.FLOAT.fieldOf("min_y").forGetter(BlendSpace2D::blendSpaceMinY),
                Codec.FLOAT.fieldOf("max_x").forGetter(BlendSpace2D::blendSpaceMaxX),
                Codec.FLOAT.fieldOf("max_y").forGetter(BlendSpace2D::blendSpaceMaxY),
                Codec.BOOL.fieldOf("loops").forGetter(BlendSpace2D::loops),
                Codec.BOOL.optionalFieldOf("wrap_x", false).forGetter(BlendSpace2D::wrapX),
                Codec.BOOL.optionalFieldOf("wrap_y", false).forGetter(BlendSpace2D::wrapY),
                AnimationNode.CODEC.listOf().fieldOf("nodes").forGetter(bs2d -> new ArrayList<>(bs2d.nodeSpace.getAllPoints()))
            )
            .apply(instance, BlendSpace2D::new)
    );

    public static final Codec<BlendSpace2D> CODEC = MAP_CODEC.codec();

    private final float fadeInTime;
    private final float fadeOutTime;
    private final float smoothX;
    private final float smoothY;
    private final boolean loops;
    private final boolean wrapX;
    private final boolean wrapY;
    private final DelaunayTriangulation<AnimationNode> nodeSpace;

    private BlendSpace2D(
        float fadeInTime,
        float fadeOutTime,
        float smoothX,
        float smoothY,
        float minX,
        float minY,
        float maxX,
        float maxY,
        boolean loops,
        boolean wrapX,
        boolean wrapY,
        List<AnimationNode> nodes
    ) {
        this.loops = loops;
        this.wrapX = wrapX;
        this.wrapY = wrapY;
        this.fadeInTime = fadeInTime;
        this.fadeOutTime = fadeOutTime;
        this.smoothX = smoothX;
        this.smoothY = smoothY;

        nodeSpace = new DelaunayTriangulation<>(minX, minY, maxX, maxY, AnimationNode::createDefaultFromXY);

        for (AnimationNode node : nodes) {
            nodeSpace.addPoint(node);
        }

        nodeSpace.reloadTriangles();
        // Should block further point generations after all blend spaces are generated by triangulation.
    }

    /// Blend space pose must be returned by [BlendSpace2DDriver#getPose], reflecting control point.
    @Override @Deprecated
    public Pose getPose(final float time) {
        return Pose.EMPTY_POSE;
    }

    @Override
    public float fadeInTime() {
        return fadeInTime;
    }

    @Override
    public float fadeOutTime() {
        return fadeOutTime;
    }

    @Override
    public float getTotalFrameTime() {
        return Float.MAX_VALUE;
    }

    @Override
    public boolean loops() {
        return loops;
    }

    /// This blend space over the mirrored twins of its nodes' animations, see
    /// [PlayableAnimation#mirrored]. Node coordinates and space bounds are unchanged, and the
    /// triangulation is rebuilt.
    @Override
    public BlendSpace2D mirrored() {
        List<AnimationNode> mirroredNodes = getNodes().stream()
            .map(node -> new AnimationNode(node.x(), node.y(), node.animation(), !node.mirrored()))
            .toList();

        return new BlendSpace2D(
            fadeInTime, fadeOutTime, smoothX, smoothY,
            blendSpaceMinX(), blendSpaceMinY(), blendSpaceMaxX(), blendSpaceMaxY(),
            loops, wrapX, wrapY, mirroredNodes
        );
    }

    @Override
    public void tick(ComponentAttachable owner, float prevElapsedTime, float currentElapsedTime) {
    }

    @Override
    public void frameUpdate(ComponentAttachable owner, float prevElapsedTime, float currentElapsedTime) {
    }

    @Override
    public void interrupt(ComponentAttachable owner, float lastTickTime, float lastFrameTime) {
    }

    public float smoothX() {
        return smoothX;
    }

    public float smoothY() {
        return smoothY;
    }

    public boolean wrapX() {
        return wrapX;
    }

    public boolean wrapY() {
        return wrapY;
    }

    public float blendSpaceMinX() {
        return nodeSpace.minX();
    }

    public float blendSpaceMinY() {
        return nodeSpace.minY();
    }

    public float blendSpaceMaxX() {
        return nodeSpace.maxX();
    }

    public float blendSpaceMaxY() {
        return nodeSpace.maxY();
    }

    /// Returns the node space for read-only access. The field itself stays private.
    public DelaunayTriangulation<AnimationNode> getNodeSpace() {
        return nodeSpace;
    }

    /// Returns all animation nodes as a list of [DelaunayTriangulation.DelaunayPoint].
    public List<AnimationNode> getNodes() {
        return new ArrayList<>(nodeSpace.getAllPoints());
    }

    @Override
    public @NonNull String toString() {
        return StaticRegistryAccess.getRegisteredName(AkytheraRegistries.DataPack.BLEND_SPACE_2D_KEY, this);
    }

    public static BlendSpace2DDriver instantiate(Holder<@NonNull BlendSpace2D> holder, final Supplier<Float> xUpdater, final Supplier<Float> yUpdater) {
        return new BlendSpace2DDriver(holder, xUpdater, yUpdater);
    }

    public static class AnimationNode implements DelaunayTriangulation.DelaunayPoint {
        /// A reference to an [AnimationMontage] or [AnimationSequence] entry. JSON shape:
        ///
        /// ```
        /// { "type": "sequence", "sequence": "akythera:anim2" }
        /// or,
        /// { "type": "montage", "montage": "akythera:anim1" }
        /// ```
        private static final Codec<ResourceKey<? extends @NonNull PlayableAnimation>> ANIMATION_KEY_CODEC = Codec.STRING.dispatch(
            "type",
            AnimationNode::tagOf,
            AnimationNode::keyCodecOf
        );

        public static final Codec<AnimationNode> CODEC = RecordCodecBuilder.create(
            instance ->
                instance.group(
                    Codec.FLOAT.fieldOf("x").forGetter(AnimationNode::x),
                    Codec.FLOAT.fieldOf("y").forGetter(AnimationNode::y),
                    ANIMATION_KEY_CODEC.optionalFieldOf("animation").forGetter(ParseUtils.provideOptional(AnimationNode::animation))
                )
                .apply(instance, (x, y, animation) -> new AnimationNode(x, y, animation.orElse(null), false))
        );

        private static MapCodec<? extends ResourceKey<? extends @NonNull PlayableAnimation>> keyCodecOf(final String tag) {
            return switch (tag) {
                case "montage" -> ResourceKey.codec(AkytheraRegistries.DataPack.ANIM_MONTAGE_KEY).fieldOf("montage");
                case "sequence" -> ResourceKey.codec(AkytheraRegistries.DataPack.ANIM_SEQUENCE_KEY).fieldOf("sequence");
                default -> throw new IllegalArgumentException("Unknown blend space node animation type: '" + tag + "' (expected 'montage' or 'sequence')");
            };
        }

        private static String tagOf(final ResourceKey<? extends @NonNull PlayableAnimation> animationKey) {
            if (animationKey.isFor(AkytheraRegistries.DataPack.ANIM_MONTAGE_KEY)) return "montage";
            if (animationKey.isFor(AkytheraRegistries.DataPack.ANIM_SEQUENCE_KEY)) return "sequence";

            throw new IllegalStateException("Unsupported blend space node animation registry: " + animationKey.registry());
        }

        private final float x;
        private final float y;

        /// The animation this node plays, or null for an empty node.
        private final @Nullable ResourceKey<? extends @NonNull PlayableAnimation> animation;

        /// Whether this node plays the mirrored twin of [#animation], see [PlayableAnimation#mirrored].
        private final boolean mirrored;
        private int index;

        /// Generate empty node, used by Akythera Labs
        public static AnimationNode createDefaultFromXY(final float x, final float y) {
            return new AnimationNode(x, y, null, false);
        }

        public AnimationNode(
            final float x, final float y, final @Nullable ResourceKey<? extends @NonNull PlayableAnimation> animation, final boolean mirrored
        ) {
            this.x = x;
            this.y = y;
            this.animation = animation;
            this.mirrored = mirrored;
        }

        /// The animation [#animation] names, mirrored when [#mirrored]. The empty animation for an empty node, and
        /// empty when the key names no entry.
        public Optional<PlayableAnimation> resolveAnimation() {
            if (animation == null) return Optional.of(PlayableAnimation.EMPTY_ANIM_HOLDER.value());

            return ScriptType.lookupEntry(animation)
                .map(holder -> mirrored ? holder.value().mirrored() : holder.value());
        }

        @Override
        public float x() {
            return x;
        }

        @Override
        public float y() {
            return y;
        }

        @Override
        public int index() {
            return index;
        }

        public @Nullable ResourceKey<? extends @NonNull PlayableAnimation> animation() {
            return animation;
        }

        public boolean mirrored() {
            return mirrored;
        }

        @Override
        public void setIndex(final int index) {
            this.index = index;
        }
    }

    public static BlendSpace2DBuilder builder() {
        return new BlendSpace2DBuilder();
    }

    /// Creates [BlendSpace2D] by received nodes
    public static final class BlendSpace2DBuilder {
        boolean loops = false;
        boolean wrapX = false;
        boolean wrapY = false;
        float smoothX = 0.0F;
        float smoothY = 0.0F;
        float fadeInTime = 0.25F;
        float fadeOutTime = 0.25F;
        float minX = -180.0F;
        float minY = 0.0F;
        float maxX = 180.0F;
        float maxY = 1.0F;
        final List<AnimationNode> nodes = new ArrayList<>();

        public BlendSpace2DBuilder smoothX(final float smoothX) {
            if (MathUtils.getSign(smoothX) == -1) {
                throw new IllegalArgumentException("smooth time can't be negative");
            }

            this.smoothX = smoothX;
            return this;
        }

        public BlendSpace2DBuilder smoothY(final float smoothY) {
            if (MathUtils.getSign(smoothX) == -1) {
                throw new IllegalArgumentException("smooth time can't be negative");
            }

            this.smoothY = smoothY;
            return this;
        }

        public BlendSpace2DBuilder loops(final boolean loops) {
            this.loops = loops;
            return this;
        }

        public BlendSpace2DBuilder wrapX(final boolean wrapX) {
            this.wrapX = wrapX;
            return this;
        }

        public BlendSpace2DBuilder wrapY(final boolean wrapY) {
            this.wrapY = wrapY;
            return this;
        }

        public BlendSpace2DBuilder fadeInTime(final float fadeInTime) {
            this.fadeInTime = fadeInTime;
            return this;
        }

        public BlendSpace2DBuilder fadeOutTime(final float fadeOutTime) {
            this.fadeOutTime = fadeOutTime;
            return this;
        }

        public BlendSpace2DBuilder minX(final float minX) {
            this.minX = minX;
            return this;
        }

        public BlendSpace2DBuilder minY(final float minY) {
            this.minY = minY;
            return this;
        }

        public BlendSpace2DBuilder maxX(final float maxX) {
            this.maxX = maxX;
            return this;
        }

        public BlendSpace2DBuilder maxY(final float maxY) {
            this.maxY = maxY;
            return this;
        }

        public BlendSpace2DBuilder putNode(final float x, final float y, final @Nullable ResourceKey<? extends @NonNull PlayableAnimation> animation) {
            nodes.add(new AnimationNode(x, y, animation, false));
            return this;
        }

        /// A node playing the entry `animation` holds. A holder with no key makes an empty node.
        public BlendSpace2DBuilder putNode(final float x, final float y, final Holder<? extends @NonNull PlayableAnimation> animation) {
            return putNode(x, y, animation.unwrapKey().orElse(null));
        }

        public BlendSpace2D create() {
            return new BlendSpace2D(
                fadeInTime,
                fadeOutTime,
                smoothX,
                smoothY,
                minX,
                minY,
                maxX,
                maxY,
                loops,
                wrapX,
                wrapY,
                nodes
            );
        }
    }
}