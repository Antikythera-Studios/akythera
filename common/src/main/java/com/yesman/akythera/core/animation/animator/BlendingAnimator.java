package com.yesman.akythera.core.animation.animator;

import com.yesman.akythera.api.animation.animator.AbstractAnimationInterface;
import com.yesman.akythera.api.animation.animator.AnimationInterfaceKey;
import com.yesman.akythera.api.animation.animator.AnimationLayer;
import com.yesman.akythera.api.animation.animator.Animator;
import com.yesman.akythera.api.component.ComponentAttachable;
import com.yesman.akythera.api.component.impl.ArmatureComponent;
import com.yesman.akythera.api.event.BuiltInEventHooks;
import com.yesman.akythera.api.event.entity.animation.InitBlendingAnimatorEvent;
import com.yesman.akythera.core.animation.AnimationLayerSignature;
import com.yesman.akythera.core.animation.driver.*;
import com.yesman.akythera.core.animation.keyframe.Pose;
import com.yesman.akythera.core.animation.playable.AnimationMontage;
import com.yesman.akythera.core.animation.playable.PlayableAnimation;
import com.yesman.akythera.core.asset.armature.Armature;
import com.yesman.akythera.core.blueprint.script.AnimatorScript;
import com.yesman.akythera.core.util.StaticRegistryAccess;
import net.minecraft.core.Holder;
import net.minecraft.resources.ResourceKey;
import org.jetbrains.annotations.ApiStatus;
import org.jspecify.annotations.NonNull;
import org.jspecify.annotations.Nullable;

import java.util.Collection;
import java.util.HashMap;
import java.util.Map;
import java.util.Set;
import java.util.function.Function;

/// An animator consists of multiple [AnimationPlayer], allowing blending
/// each pose resulted by animation players.
///
/// Belonged to client side entities where requires complex animation logics
/// for lifecycle motions and procedural animation processing decided by the
/// owner's state or nearby terrain & entities.
///
/// Detailed logics should be implemented in [AnimatorScript].
public final class BlendingAnimator implements Animator {
    private ComponentAttachable owner;

    /// Defines how this animator is controlled in each event trigger
    private final AnimatorScript animScript;

    /// Anim interfaces belonged to this animator. Do not manually modify the entries
    @ApiStatus.Internal
    private final Map<AnimationInterfaceKey, AbstractAnimationInterface> animInterfaces = new HashMap<>();

    /// Animation layer map. Do not manually modify the entries
    @ApiStatus.Internal
    private final Map<AnimationLayerSignature, AnimationLayer> animLayers = new HashMap<> ();

    /// For poses that will be reused throughout multiple layers. Do not modify the entries
    @ApiStatus.Internal
    private final Map<String, AnimationDriver> cachedPoseDrivers = new HashMap<> ();

    /// A pose cache generated by [#cachedPoseDrivers]
    private final Map<String, Pose> cachedPoses = new HashMap<>();

    public boolean isHardPaused = false;
    public boolean isSoftPaused = false;

    /// @param owner Owner of the animator, must match the type with animator script
    public BlendingAnimator(final ComponentAttachable owner, final Function<Animator, AnimatorScript> animScriptProvider)
        throws RuntimeException
    {
        this.owner = owner;
        this.animScript = animScriptProvider.apply(this);

        animScript.construct(animLayers, cachedPoseDrivers, this);
        BuiltInEventHooks.Animation.INIT_BLENDING_ANIMATOR.post(new InitBlendingAnimatorEvent(owner, animScript, this));
    }

    /// Register animation interfaces. (initializer)
    ///
    /// [AbstractAnimationInterface] holds initial animation which is set as default. They can be modified by
    /// [#replaceAnimation], and rolled back by either [#resetAnimInterface] or [#resetAllInterfaces]
    public void addAnimInterface(final AnimationInterfaceKey key, final AbstractAnimationInterface animInterface) {
        // In case add-ons declare the same key twice, it needs to be fixed.
        if (animInterfaces.containsKey(key))
            throw new IllegalStateException("Animation Interface key `" + key + "` is already in use");

        animInterfaces.put(key, animInterface);
    }

    /// Replace animation by interface key, through animation interface. This keeps the default animation info in interface
    /// so it can be rolled back to default animation anytime.
    ///
    /// This function has no effect if no key exists.
    public void replaceAnimation(final AnimationInterfaceKey key, final Holder<? extends PlayableAnimation> animation) {
        if (animInterfaces.containsKey(key)) animInterfaces.get(key).replace(animation);
    }

    /// Reset animation interfaces to [AbstractAnimationInterface#reset]
    public void resetAnimInterface(final AnimationInterfaceKey key) {
        if (animInterfaces.containsKey(key)) animInterfaces.get(key).reset();
    }

    /// Reset every interface to default one
    public void resetAllInterfaces() {
        animInterfaces.values().forEach(AbstractAnimationInterface::reset);
    }

    /// Rolls every interface but the ones `keep` names back to its default animation.
    public void resetInterfacesExcept(final Set<AnimationInterfaceKey> keep) {
        animInterfaces.forEach((key, animInterface) -> {
            if (!keep.contains(key)) animInterface.reset();
        });
    }

    @Override
    public AnimationMontagePlayer getMontagePlayer(final ResourceKey<@NonNull AnimationMontage> animMontageKey) {
        Holder.Reference<AnimationMontage> montage = StaticRegistryAccess.getRegistryAccess().getOrThrow(animMontageKey);
        return animLayers.get(montage.value().layerSignature()).montagePlayer();
    }

    @Override
    public Collection<AnimationMontagePlayer> getMontagePlayers() {
        return animLayers.values().stream().map(AnimationLayer::montagePlayer).toList();
    }

    @Override
    public void tick() {
        for (AnimationLayer animLayer : animLayers.values()) {
            animLayer.tick(owner);
        }
    }

    @Override
    public void update(final float frameTime, final float partialTick) {
        animScript.update(frameTime, partialTick);

        for (AnimationLayer animLayer : animLayers.values()) {
            animLayer.update(frameTime);
        }

        // Reset cached poses
        cachedPoses.clear();
    }

    @Override
    public void setSoftPause(final boolean paused) {
        this.isSoftPaused = paused;
    }

    @Override
    public void setHardPause(final boolean paused) {
        this.isHardPaused = paused;
    }

    @Override
    public boolean isSoftPaused() {
        return isSoftPaused;
    }

    @Override
    public boolean isHardPaused() {
        return isHardPaused;
    }

    @Override
    public Pose getPose() {
        Pose pose = animScript.getFinalPose(animLayers);
        ArmatureComponent armatureComponent = owner.findComponent(ArmatureComponent.class);
        Armature armature = armatureComponent == null ? null : armatureComponent.getArmature().get();

        return armature == null ? pose : armature.applyJointConstraints(pose);
    }

    /// Presence of named pose cache must be validated first. Use [#hasPoseCache] to conduct it.
    public AnimationDriver getCachedPoseDriver(final String cacheName) throws IllegalStateException {
        if (!cachedPoseDrivers.containsKey(cacheName)) throw new IllegalStateException("No pose cache for " + cacheName);
        return cachedPoseDrivers.get(cacheName);
    }

    public boolean hasPoseCache(final String cacheName) {
        return cachedPoseDrivers.containsKey(cacheName);
    }

    public @Nullable Pose getCachedPose(final String cacheName) {
        return cachedPoses.get(cacheName);
    }

    /// Called by [CachedPoseReference]. Don't make custom call.
    @ApiStatus.Internal
    public void cachePose(final String cacheName, final Pose pose) {
        cachedPoses.put(cacheName, pose);
    }

    @SuppressWarnings("unchecked") @Override
    public <O> O getOwner() {
        return (O)owner;
    }

    @Override
    public void setOwner(final ComponentAttachable owner) {
        this.owner = owner;
    }
}
