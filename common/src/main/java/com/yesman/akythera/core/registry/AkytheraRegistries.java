package com.yesman.akythera.core.registry;

import com.mojang.serialization.MapCodec;
import com.yesman.akythera.api.input.InputAction;
import com.yesman.akythera.core.blueprint.AbilityCueBlueprint;
import com.yesman.akythera.api.world.patch.entity.EntityPatch;
import com.yesman.akythera.core.blueprint.script.DataDrivenAnimatorScript;
import com.yesman.akythera.api.animation.notify.AnimationNotify;
import com.yesman.akythera.api.animation.notify.AnimationNotifyState;
import com.yesman.akythera.api.data.modularize.ScriptFunction;
import com.yesman.akythera.api.data.modularize.ScriptType;
import com.yesman.akythera.core.Akythera;
import com.yesman.akythera.core.animation.playable.AnimationMontage;
import com.yesman.akythera.core.animation.playable.AnimationSequence;
import com.yesman.akythera.core.animation.playable.BlendSpace2D;
import com.yesman.akythera.core.blueprint.EntityPatchBlueprint;
import com.yesman.akythera.core.blueprint.ItemPatchBlueprint;
import com.yesman.akythera.core.blueprint.ComponentBlueprint;
import com.yesman.akythera.platform.ModPlatformProvider;
import net.minecraft.core.Registry;
import com.yesman.akythera.api.world.ability.AbilityEffect;
import com.yesman.akythera.core.blueprint.AbilityBlueprint;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.item.Item;
import org.jspecify.annotations.NullMarked;

@NullMarked
public final class AkytheraRegistries {
    private AkytheraRegistries() {}

    private static <T> ResourceKey<Registry<T>> createRegistryKey(String name) {
        return ResourceKey.createRegistryKey(Akythera.identifier(name));
    }

    /// Registries that are synchronized in joining a world, that entries are generated by data pack
    public static final class DataPack {
        private DataPack() {}

        // Keys
        public static final ResourceKey<Registry<AnimationMontage>> ANIM_MONTAGE_KEY = createRegistryKey("anim_montage");
        public static final ResourceKey<Registry<AnimationSequence>> ANIM_SEQUENCE_KEY = createRegistryKey("anim_sequence");
        public static final ResourceKey<Registry<DataDrivenAnimatorScript.AnimatorScriptBlueprint>> ANIMATOR_SCRIPT_KEY = createRegistryKey("script/animator");
        public static final ResourceKey<Registry<BlendSpace2D>> BLEND_SPACE_2D_KEY = createRegistryKey("blend_space_2d");
        public static final ResourceKey<Registry<EntityPatchBlueprint>> ENTITY_PATCH_KEY = createRegistryKey("script/entity_patch");
        public static final ResourceKey<Registry<ItemPatchBlueprint>> ITEM_PATCH_KEY = createRegistryKey("item_patch");
        public static final ResourceKey<Registry<AbilityEffect>> ABILITY_EFFECT_KEY = createRegistryKey("ability_effect");
        public static final ResourceKey<Registry<AbilityBlueprint>> ABILITY_KEY = createRegistryKey("ability");
        public static final ResourceKey<Registry<InputAction>> INPUT_ACTION_KEY = createRegistryKey("input_action");
        public static final ResourceKey<Registry<AbilityCueBlueprint>> ABILITY_CUE_KEY = createRegistryKey("ability_cue");

        static {
            ModPlatformProvider.get().createDataPackRegistry(ANIM_MONTAGE_KEY, AnimationMontage.CODEC);
            ModPlatformProvider.get().createDataPackRegistry(ANIM_SEQUENCE_KEY, AnimationSequence.CODEC);
            ModPlatformProvider.get().createDataPackRegistry(BLEND_SPACE_2D_KEY, BlendSpace2D.CODEC);
            ModPlatformProvider.get().createDataPackRegistry(ANIMATOR_SCRIPT_KEY, DataDrivenAnimatorScript.AnimatorScriptBlueprint.CODEC);
            ModPlatformProvider.get().createDataPackRegistry(ENTITY_PATCH_KEY, EntityPatchBlueprint.CODEC);
            ModPlatformProvider.get().createDataPackRegistry(ITEM_PATCH_KEY, ItemPatchBlueprint.CODEC);
            ModPlatformProvider.get().createDataPackRegistry(ABILITY_EFFECT_KEY, AbilityEffect.CODEC);
            ModPlatformProvider.get().createDataPackRegistry(ABILITY_KEY, AbilityBlueprint.CODEC);
            ModPlatformProvider.get().createDataPackRegistry(INPUT_ACTION_KEY, InputAction.CODEC);
            ModPlatformProvider.get().createDataPackRegistry(ABILITY_CUE_KEY, AbilityCueBlueprint.CODEC);
        }
    }

    /// Registries that are created when the game launches. Entries are frozen to prevent runtime modification.
    public static final class Frozen {
        private Frozen() {}

        // Keys
        public static final ResourceKey<Registry<MapCodec<? extends AnimationNotify<?>>>> ANIM_NOTIFY_TYPE_KEY = createRegistryKey("anim_notify_type");
        public static final ResourceKey<Registry<MapCodec<? extends AnimationNotifyState<?>>>> ANIM_NOTIFY_STATE_TYPE_KEY = createRegistryKey("anim_notify_state_type");
        public static final ResourceKey<Registry<ScriptFunction>> SCRIPT_FUNCTION_KEY = createRegistryKey("script_function");
        public static final ResourceKey<Registry<ScriptType>> SCRIPT_TYPE_KEY = createRegistryKey("script_type");
        public static final ResourceKey<Registry<MapCodec<? extends ComponentBlueprint<?, ?>>>> ENTITY_PATCH_COMPONENT_TYPES_KEY = createRegistryKey("entity_patch_component_type");
        public static final ResourceKey<Registry<MapCodec<? extends ComponentBlueprint<?, ?>>>> ITEM_PATCH_COMPONENT_TYPES_KEY = createRegistryKey("item_patch_component_type");

        // Registries
        public static final Registry<MapCodec<? extends AnimationNotify<?>>> ANIM_NOTIFY_TYPES = ModPlatformProvider.get().createRegistry(ANIM_NOTIFY_TYPE_KEY);
        public static final Registry<MapCodec<? extends AnimationNotifyState<?>>> ANIM_NOTIFY_STATE_TYPES = ModPlatformProvider.get().createRegistry(ANIM_NOTIFY_STATE_TYPE_KEY);
        public static final Registry<ScriptFunction> SCRIPT_FUNCTION = ModPlatformProvider.get().createRegistry(SCRIPT_FUNCTION_KEY);
        public static final Registry<ScriptType> SCRIPT_TYPE = ModPlatformProvider.get().createRegistry(SCRIPT_TYPE_KEY);

        /// Component types an [EntityPatchBlueprint] and its hosts may attach.
        public static final Registry<MapCodec<? extends ComponentBlueprint<?, ?>>> ENTITY_PATCH_COMPONENT_TYPES = ModPlatformProvider.get().createRegistry(ENTITY_PATCH_COMPONENT_TYPES_KEY);

        /// Component types an [ItemPatchBlueprint] and its hosts may attach.
        public static final Registry<MapCodec<? extends ComponentBlueprint<?, ?>>> ITEM_PATCH_COMPONENT_TYPES = ModPlatformProvider.get().createRegistry(ITEM_PATCH_COMPONENT_TYPES_KEY);
    }
}
